#!/bin/bash
# Usage: entrypoint.sh login|game
# Applies overrides, renders container-specific settings and starts the server in the foreground.
set -euo pipefail

ROLE="${1:?usage: entrypoint.sh login|game}"
DIST=/opt/l2/dist
DIR="$DIST/$ROLE"
CFG="$DIR/config"

# Defaults from L2J's own Docker images; JAVA_OPTS comes later on the command line, so its -Xmx wins
case "$ROLE" in
	login) JAR=l2jlogin.jar MEM="-Xms128m -Xmx256m" ;;
	game) JAR=l2jserver.jar MEM="-Xms1g -Xmx2g" ;;
	*) echo "Unknown role: $ROLE" >&2; exit 1 ;;
esac

# props_set <file> <key> <value> - replaces "Key = ..." keeping the file layout
props_set() {
	local value="${3//\\/\\\\}"
	value="${value//&/\\&}"
	value="${value//|/\\|}"
	sed -i -E "s|^$2[[:space:]]*=.*$|$2 = $value|" "$1"
}

# 1. User overrides (overrides/l2j/<role>/... mirrors dist/<role>/...)
if [ -d "/overrides/$ROLE" ]; then
	echo "Applying overrides from /overrides/$ROLE"
	cp -rf "/overrides/$ROLE/." "$DIR/"
fi

DB_URL="jdbc:mariadb://${DB_HOST:-db}/${MARIADB_DATABASE}"

# 2. Database connection (values from .env always win) and networking between containers. The login server
# and the High Five game server use database.properties; the Interlude game server (older layout) keeps the
# database in server.properties. UPnP makes no sense behind Docker's NAT.
if [ -f "$CFG/database.properties" ]; then
	props_set "$CFG/database.properties" URL "$DB_URL"
	props_set "$CFG/database.properties" User "$MARIADB_USER"
	props_set "$CFG/database.properties" Password "$MARIADB_PASSWORD"
	props_set "$CFG/server.properties" EnableUPnP False
else
	props_set "$CFG/server.properties" Driver org.mariadb.jdbc.Driver
	props_set "$CFG/server.properties" URL "$DB_URL"
	props_set "$CFG/server.properties" Login "$MARIADB_USER"
	props_set "$CFG/server.properties" Password "$MARIADB_PASSWORD"
fi

if [ "$ROLE" = login ]; then
	props_set "$CFG/server.properties" GameServerHost "*"
else
	props_set "$CFG/server.properties" LoginHost "${LOGIN_HOST:-login}"

	# Interlude: geodata is off by default and loaded from data/geodata/geo_index.txt. With region files
	# present it is switched to line of sight and movement checks (1), and a missing index is generated.
	if [ -f "$CFG/options.properties" ]; then
		regions="$(ls "$DIR/data/geodata" 2>/dev/null | sed -n 's/^\([0-9]*_[0-9]*\)\.l2j$/\1/p')"
		if [ -n "$regions" ]; then
			props_set "$CFG/options.properties" GeoData 1
			[ -f "$DIR/data/geodata/geo_index.txt" ] || printf '%s\n' $regions > "$DIR/data/geodata/geo_index.txt"
		fi
		# java.util.logging writes to log/; the mounted directory is logs/
		[ -e "$DIR/log" ] || ln -s logs "$DIR/log"
	fi

	# Address sent to clients. Kept if the user provided ipconfig.xml in overrides.
	if [ ! -f "/overrides/game/config/ipconfig.xml" ]; then
		cat > "$CFG/ipconfig.xml" <<-EOF
		<?xml version="1.0" encoding="UTF-8"?>
		<!-- Generated by entrypoint.sh from EXTERNAL_HOST. Put your own file in overrides/l2j/game/config/ to replace it. -->
		<gameserver address="${EXTERNAL_HOST:-127.0.0.1}" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="ipconfig.xsd">
			<define subnet="127.0.0.0/8" address="127.0.0.1" />
		</gameserver>
		EOF
	fi

	# The game server gets its hex id from the login server on first start and saves it as config/hexid.txt;
	# the link keeps it in the game-state volume across container re-creation
	if [ -d /state ]; then
		[ -f "$CFG/hexid.txt" ] && [ ! -L "$CFG/hexid.txt" ] && [ ! -f /state/hexid.txt ] && cp "$CFG/hexid.txt" /state/hexid.txt
		ln -sf /state/hexid.txt "$CFG/hexid.txt"
	fi
fi

# 4. Start in the foreground so logs go to "docker logs" and Docker handles restarts
mkdir -p "$DIR/logs"
cd "$DIR"
# shellcheck disable=SC2086
exec java $MEM ${JAVA_OPTS:-} -jar "$JAR"
