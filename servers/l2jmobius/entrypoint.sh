#!/bin/bash
# Usage: entrypoint.sh login|game
# Applies overrides, renders container-specific settings and starts the server in the foreground.
set -euo pipefail

ROLE="${1:?usage: entrypoint.sh login|game}"
DIST=/opt/l2/dist
DIR="$DIST/$ROLE"
CFG="$DIR/config"

case "$ROLE" in
	login) JAR=LoginServer.jar ;;
	game) JAR=GameServer.jar ;;
	*) echo "Unknown role: $ROLE" >&2; exit 1 ;;
esac

# ini_set <file> <key> <value> - replaces "Key = ..." keeping the file layout
ini_set() {
	local value="${3//\\/\\\\}"
	value="${value//&/\\&}"
	value="${value//|/\\|}"
	sed -i -E "s|^$2[[:space:]]*=.*$|$2 = $value|" "$1"
}

# 1. User overrides (overrides/<role>/... mirrors dist/<role>/...)
if [ -d "/overrides/$ROLE" ]; then
	echo "Applying overrides from /overrides/$ROLE"
	cp -rf "/overrides/$ROLE/." "$DIR/"
fi

# 2. Database connection (values from .env always win)
DB_URL="jdbc:mysql://${DB_HOST:-db}/${MARIADB_DATABASE}?useUnicode=true&characterEncoding=utf-8&allowPublicKeyRetrieval=true&useSSL=false&connectTimeout=10000&interactiveClient=true&sessionVariables=wait_timeout=600,interactive_timeout=600&autoReconnect=true"
ini_set "$CFG/Database.ini" URL "$DB_URL"
ini_set "$CFG/Database.ini" Login "$MARIADB_USER"
ini_set "$CFG/Database.ini" Password "$MARIADB_PASSWORD"

# 3. Headless: no Swing GUI inside a container
[ -f "$CFG/Interface.ini" ] && ini_set "$CFG/Interface.ini" EnableGUI False

# 4. Networking between containers
if [ "$ROLE" = login ]; then
	ini_set "$CFG/Server.ini" LoginHostname 0.0.0.0
else
	ini_set "$CFG/Server.ini" LoginHost "${LOGIN_HOST:-login}"

	# Address sent to clients. Kept if the user provided ipconfig.xml in overrides.
	# The second define only repeats the default address: older chronicles (C1) send the third host entry
	# to the login server unconditionally and fail to register with fewer.
	if [ ! -f "/overrides/game/config/ipconfig.xml" ]; then
		cat > "$CFG/ipconfig.xml" <<-EOF
		<?xml version="1.0" encoding="UTF-8"?>
		<!-- Generated by entrypoint.sh from EXTERNAL_HOST. Put your own file in overrides/l2jmobius/game/config/ to replace it. -->
		<gameserver address="${EXTERNAL_HOST:-127.0.0.1}" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="../data/xsd/ipconfig.xsd">
			<define subnet="127.0.0.0/8" address="127.0.0.1" />
			<define subnet="10.0.0.0/8" address="${EXTERNAL_HOST:-127.0.0.1}" />
		</gameserver>
		EOF
	fi

	# Keep hexid.txt (game server registration) across container re-creation
	if [ -d /state ]; then
		[ -f /state/hexid.txt ] || cp "$CFG/hexid.txt" /state/hexid.txt
		ln -sf /state/hexid.txt "$CFG/hexid.txt"
	fi
fi

# 5. Start in the foreground so logs go to "docker logs" and Docker handles restarts
mkdir -p "$DIR/log"
cd "$DIR"
# JAVA_OPTS is appended after java.cfg, so e.g. -Xmx given there takes precedence
# shellcheck disable=SC2046,SC2086
exec java $(cat java.cfg) ${JAVA_OPTS:-} -jar "../libs/$JAR"
